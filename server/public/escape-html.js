// Экранирование пользовательского текста перед вставкой через innerHTML.
//
// Чат эфира, личные сообщения и таблица админки собирают разметку шаблонными
// строками и присваивают её innerHTML. Значения там приходят из базы, то есть
// от пользователей: сообщение с <img src=x onerror=...> выполнялось у всех,
// кто открыл страницу. Серверный рендер этим не защищён — он экранирует
// только <%= %>, а эти куски собираются уже в браузере.
//
// escapeHtml годится и для текста между тегами, и для значения атрибута
// в кавычках: экранируются < > & " '.
(function (global) {
  var MAP = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

  global.escapeHtml = function escapeHtml(value) {
    if (value === null || value === undefined) return '';
    return String(value).replace(/[&<>"']/g, function (ch) { return MAP[ch]; });
  };
})(window);
