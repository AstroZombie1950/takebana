// -----------------------------
// Global i18n runtime (RU/EN)
// - Uses `localStorage.lang`
// - Applies translations to elements with attribute: lng="123"
// - Updates placeholders for INPUT/TEXTAREA (HTML stripped)
// - Safe to include on every page
// -----------------------------
(function () {
  try {
    // Expose dictionary for other scripts if needed
    if (typeof window !== 'undefined') {
      window.langDict = lang;
    }

    const DEFAULT_LANG = 'ru';
    const STORAGE_KEY = 'lang';

    const stripHtml = (s) => String(s).replace(/<[^>]*>/g, '');

    function applyLang(nextLang) {
      const langKey = (nextLang === 'en' || nextLang === 'ru') ? nextLang : DEFAULT_LANG;

      // Update header label if present
      const languageToggle = document.getElementById('languageToggle');
      if (languageToggle) {
        const label = languageToggle.querySelector('span');
        if (label) label.textContent = langKey.toUpperCase();
      }

      // Translate all nodes with lng="..."
      const nodes = document.querySelectorAll('[lng]');
      nodes.forEach((el) => {
        const key = el.getAttribute('lng');
        if (!key || !lang[key] || typeof lang[key][langKey] === 'undefined') return;

        const translation = lang[key][langKey];
        const tag = (el.tagName || '').toUpperCase();

        if (tag === 'INPUT' || tag === 'TEXTAREA') {
          el.placeholder = stripHtml(translation);
          return;
        }

        el.innerHTML = translation;
      });
    }

    // Global helper: t('123') -> translated string for current lang (ru/en)
    function t(key) {
      const langKey = (localStorage.getItem(STORAGE_KEY) === 'en') ? 'en' : 'ru';
      const v = lang && lang[key] && typeof lang[key][langKey] !== 'undefined' ? lang[key][langKey] : '';
      return v;
    }

    // Allow header (or other scripts) to force-apply language
    if (typeof window !== 'undefined') {
      window.applyLang = applyLang;
      window.t = t;
    }

    function initI18n() {
      const saved = localStorage.getItem(STORAGE_KEY) || DEFAULT_LANG;
      applyLang(saved);

      // Click handling for dropdown buttons: <button data-lang="ru|en">
      // Important: bind once even if initI18n is called multiple times.
      if (!window.__i18nClickBound) {
        window.__i18nClickBound = true;
        // Use capture phase so other handlers can't stop this (common in complex headers)
        document.addEventListener('click', (e) => {
          const btn = e.target && e.target.closest ? e.target.closest('[data-lang]') : null;
          if (!btn) return;

          const next = btn.getAttribute('data-lang');
          if (next !== 'ru' && next !== 'en') return;

          localStorage.setItem(STORAGE_KEY, next);
          applyLang(next);

          const dropdown = document.getElementById('languageDropdown');
          if (dropdown) dropdown.classList.add('hidden');
        }, true);
      }
    }

    // Init even if script is loaded after DOMContentLoaded
    if (document.readyState === 'loading') {
      document.addEventListener('DOMContentLoaded', initI18n);
    } else {
      initI18n();
    }
  } catch (err) {
    // Never break the page if i18n fails
    console.warn('[i18n] failed to init', err);
  }
})();