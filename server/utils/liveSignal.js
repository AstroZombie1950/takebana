// «Кто сейчас в эфире» — живым сигналом, а не только перезагрузкой страницы.
//
// До 20.09.2026 о начале и конце эфира узнавали лишь те, кто уже стоял на его
// странице: `stream:update` уходит в комнату `stream:<ключ>` и никуда больше.
// Витрина, список авторов и левая панель показывали то, что было на момент
// отрисовки, и не менялись, пока человек не обновит страницу. Заодно «в эфире»
// в левой панели не работало вовсе: `shared.js` читал поле `isStreaming`,
// которого нет ни в схеме User, ни в одном документе базы, — статус всегда
// выходил «не в эфире», а счётчик «N в эфире» всегда нулём.
//
// Отсюда уходят два сигнала:
//
//   author:live   — в комнату `presence:<id>` автора. Эти комнаты уже есть:
//                   клиент подписывается на них для точек «в сети» по всем
//                   [data-presence-user] на экране (public/tk-app.js). Значит
//                   каждый, у кого автор виден на странице, узнаёт о его
//                   эфире, и новой машинерии подписок не нужно.
//
//   live:changed  — в комнату `live`, куда входят страницы со списком идущих
//                   эфиров (витрина, /authors). Они перечитывают свою сетку.
//                   Без названий и ключей: сетку всё равно отдаёт сервер,
//                   а рассылать состав эфира всем подряд незачем.

const errorLog = require('./errorLog');

const LIVE_ROOM = 'live';

// io может не быть (скрипты, тесты), userId — не быть у брошенного эфира.
// Ни то ни другое не повод ронять завершение эфира.
function changed(io, userId, live) {
  if (!io) return;
  try {
    if (userId) io.to(`presence:${String(userId)}`).emit('author:live', { userId: String(userId), live: !!live });
    io.to(LIVE_ROOM).emit('live:changed', { live: !!live });
  } catch (e) {
    errorLog.server(e, 'liveSignal.changed', { userId: String(userId || ''), live: !!live });
  }
}

module.exports = { changed, LIVE_ROOM };
