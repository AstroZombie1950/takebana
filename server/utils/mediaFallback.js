// Запасная дорога к медиа: те же файлы, но нашим адресом.
//
// Зачем. 23.09.2026 один и тот же человек с одного и того же телефона
// прошёл проверку связи (/check) дважды подряд: через VPN (Melbicom, DE) —
// всё открылось, без VPN (Irtelcom, RU) — сайт за 257 мс, Daily и TURN
// живы, а обе зоны Bunny молчали до таймаута, ноль байт из 98304.
// Адреса зон — 185.111.111.155 и .156, соседи по одной подсети. Значит
// режут подсеть Bunny, а не домен: переезд на свои поддомены 20.09
// (docs/CDN-DOMAIN.md) такому не помогает и помочь не мог.
//
// Для такого человека голосовые, кружки, вложения, фотографии, записи
// и веб-эфиры просто не существуют — файл есть, не открывается, ошибок
// нет. Теперь у них есть вторая дорога: через наш домен, который с той же
// сети открывается.
//
// Как. Браузер, наткнувшись на недоступный CDN, ставит cookie (chats.js,
// tk-check.js). Видя её, сервер отдаёт страницы и JSON с подменёнными
// адресами: записи — через /m/ (его проксирует nginx насквозь, на диск
// ничего не ложится), эфиры — с нашего диска путём /lf/. У обоих путей
// общий потолок (ops/nginx/takebana.conf): заблокированным — минимум.
//
// Почему подмена одна на весь ответ, а не в каждом шаблоне. Адрес CDN
// попадает в разметку и в JSON из десятка мест: карточки записей,
// галерея, вложения переписки, плеер, бесконечная лента каталога. Пройти
// по всем и не забыть ни одного — ровно тот случай, когда забудешь: один
// пропущенный адрес, и человек видит половину медиа, что хуже честного
// «не грузится». Адрес же везде один и тот же, а замена — подстрока
// в готовом ответе. Для тех, у кого cookie нет (а это все, кроме
// заблокированных), не делается вообще ничего.

const COOKIE = 'tkmedia';
const VALUE = 'own';
// Столько браузер помнит, что CDN ему не открылся. Меньше — человек будет
// снова и снова натыкаться на пустые кружки; больше — мы будем возить
// через себя трафик того, у кого сеть давно сменилась.
const DAYS = 30;

const trim = (v) => (v || '').replace(/\/+$/, '');

// Записи, голосовые, кружки, вложения, фотографии: лежат в Bunny Storage,
// раздаются pull zone. Замена — наш /m/, его проксирует nginx.
const VOD = trim(process.env.RECORDINGS_CDN_URL);
// Эфиры: их источник — наш же диск (server/media/live, nginx отдаёт по
// /live/), CDN тут только усилитель поверх нас. Прокси не нужен — замена
// /lf: тот же диск отдельным путём с потолком скорости и соединений
// (ops/nginx/takebana.conf). Не /live/ — оттуда эфир забирает сам Bunny,
// и потолок не должен его касаться (решение 25.09.2026: заблокированным —
// минимум, наш канал важнее).
const LIVE = trim(process.env.HLS_BASE_URL);

// Подмена нужна не везде. Страница проверки связи обязана ходить на
// настоящий CDN — иначе она всегда показывала бы «открывается». В панели
// адреса CDN — это данные, которые админ читает как есть.
const SKIP = /^\/(check|api\/admin)/;

function wanted(req) {
  return new RegExp('(?:^|;\\s*)' + COOKIE + '=' + VALUE + '(?:;|$)').test(req.headers.cookie || '');
}

// Адрес целиком, а не просто начало строки. Без этой проверки
// `https://vod.takebana.com.evil.net/x` — чужой домен, всего лишь похожий
// на наш, — тоже подменялся бы: начало совпадает. Поэтому за адресом
// обязан идти слэш (так выглядит ссылка на файл), кавычка или конец
// строки (так адрес зоны лежит в атрибуте и в JSON).
function boundary(origin) {
  return new RegExp(origin.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '(?=/|["\'\\s]|$)', 'g');
}

const VOD_RX = VOD && boundary(VOD);
const LIVE_RX = LIVE && boundary(LIVE);

function swap(text) {
  let out = text;
  if (VOD_RX) out = out.replace(VOD_RX, '/m');
  if (LIVE_RX) out = out.replace(LIVE_RX, '/lf');
  return out;
}

// Ответ переписывается только текстовый и только свой: разметка страниц
// и JSON маршрутов. Файлы, потоки и всё остальное проходят нетронутыми.
//
// Пустой Content-Type здесь — это html: res.render зовёт res.send без типа
// вовсе, а тип строке проставляет сам send, уже после нас (express,
// lib/response.js). Проверять только выставленный тип значило бы пропускать
// ровно страницы — то есть почти всё.
const TEXT = /^(text\/html|application\/json)/;

function middleware(req, res, next) {
  if ((!VOD && !LIVE) || SKIP.test(req.path) || !wanted(req)) return next();
  const send = res.send.bind(res);
  res.send = function sendWithOwnMedia(body) {
    if (typeof body === 'string' && TEXT.test(res.get('Content-Type') || 'text/html')) {
      // Длину ответа express считает по тому, что получил, — подменяем до
      // вызова, и Content-Length выходит верным сам.
      return send(swap(body));
    }
    return send(body);
  };
  // Один и тот же адрес отдаёт разные страницы. res.render уже помечает
  // ответы Vary: Cookie (utils/i18n.js), но JSON маршрутов через него
  // не проходит, а кэш между нами и браузером обязан их различать.
  res.vary('Cookie');
  next();
}

// Для страниц: адрес CDN и замена — браузеру, чтобы он смог подменить
// адрес сам, ещё до перезагрузки (public/chats.js).
const locals = { mediaCdn: VOD, mediaOwn: '/m', mediaCookie: COOKIE, mediaDays: DAYS };

module.exports = { middleware, locals };
